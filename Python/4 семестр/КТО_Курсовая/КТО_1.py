import numpy as np
import matplotlib.pyplot as plt

# 1. Задаём параметры задачи
L = 1.0          # длина стержня (метры)
T = 0.1          # общее время расчёта (секунды)
nx = 50          # количество интервалов по x (чем больше, тем точнее)
nt = 1000        # количество интервалов по времени

# 2. Создаём сетку
x = np.linspace(0, L, nx+1)     # точки x: от 0 до L, всего nx+1 точек
t = np.linspace(0, T, nt+1)     # точки t: от 0 до T, всего nt+1 точек

# Шаг сетки (будет нужен для численных схем)
dx = L / nx      # шаг по координате
dt = T / nt      # шаг по времени


# 3. Задаём начальное условие u(x,0)
def u0(x):
    """
    Начальное распределение температуры вдоль стержня.
    В данном случае — синусоида: максимум температуры в центре, нули на концах.
    """
    return np.sin(np.pi * x)


# 4. Задаём граничные условия Дирихле u(0,t) и u(L,t)
